package Fag.objetos;

public class Livro {

	private String titulo;
	private String altor;
	private int id;
	
	public Livro() {
	}
	
	public String getTitulo() {
		return titulo;
	}
	public void setTitulo(String titulo) {
		this.titulo = titulo;
	}
	public String getAltor() {
		return altor;
	}
	public void setAltor(String altor) {
		this.altor = altor;
	}
	public int getId() {
		return id;
	}

	public void setId(int id) {
		this.id = id;
	}

}
